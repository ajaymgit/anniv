export function getActiveLetters() {
  try {
    const saved = localStorage.getItem("mythri_custom_letters_v1");
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    console.error("Error reading saved letters:", e);
  }
  return DEFAULT_LETTERS;
}

export function saveCustomLetters(letters) {
  try {
    localStorage.setItem("mythri_custom_letters_v1", JSON.stringify(letters));
    return true;
  } catch (e) {
    console.error("Error saving custom letters:", e);
    return false;
  }
}

export function resetLettersToDefault() {
  try {
    localStorage.removeItem("mythri_custom_letters_v1");
  } catch (e) {}
  return DEFAULT_LETTERS;
}
